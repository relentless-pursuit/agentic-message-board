-- One schema for H2 (demo, MODE=PostgreSQL) and Postgres (production).

CREATE TABLE IF NOT EXISTS agents (
    handle VARCHAR(40) PRIMARY KEY,
    name VARCHAR(60) NOT NULL,
    function_text VARCHAR(200) NOT NULL,
    owner VARCHAR(80) NOT NULL,
    contact VARCHAR(120),
    visibility VARCHAR(10) NOT NULL,
    tags VARCHAR(400) NOT NULL,
    schedule VARCHAR(200) NOT NULL,
    event_trigger VARCHAR(60),
    connectors VARCHAR(400) NOT NULL,
    source VARCHAR(10) NOT NULL,
    enabled BOOLEAN NOT NULL,
    active BOOLEAN NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'Never run',
    definition TEXT NOT NULL,
    next_run_at TIMESTAMP WITH TIME ZONE,
    last_run_id BIGINT,
    last_run_status VARCHAR(12),
    last_run_at TIMESTAMP WITH TIME ZONE,
    last_post_id BIGINT,
    last_post_title VARCHAR(200),
    last_post_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_agents_owner ON agents (owner);
CREATE INDEX IF NOT EXISTS idx_agents_next_run ON agents (next_run_at);
CREATE INDEX IF NOT EXISTS idx_agents_event ON agents (event_trigger);

-- One row per run of an agent. The unique key stops the same run being created twice,
-- even when several schedulers or event listeners race each other.
CREATE TABLE IF NOT EXISTS runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_handle VARCHAR(40) NOT NULL,
    trigger_kind VARCHAR(12) NOT NULL,
    trigger_key VARCHAR(200) NOT NULL,
    trigger_detail VARCHAR(200),
    depth INT NOT NULL,
    event_payload TEXT,
    status VARCHAR(12) NOT NULL,
    worker VARCHAR(80),
    queued_at TIMESTAMP WITH TIME ZONE NOT NULL,
    started_at TIMESTAMP WITH TIME ZONE,
    finished_at TIMESTAMP WITH TIME ZONE,
    fingerprint VARCHAR(64),
    engine VARCHAR(20),
    result VARCHAR(300),
    error VARCHAR(2000),
    post_id BIGINT,
    CONSTRAINT uq_runs_trigger UNIQUE (agent_handle, trigger_key)
);
CREATE INDEX IF NOT EXISTS idx_runs_agent ON runs (agent_handle, id);
CREATE INDEX IF NOT EXISTS idx_runs_status ON runs (status, id);

CREATE TABLE IF NOT EXISTS run_steps (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL,
    seq INT NOT NULL,
    stage VARCHAR(10) NOT NULL,
    name VARCHAR(60) NOT NULL,
    status VARCHAR(10) NOT NULL,
    detail VARCHAR(2000),
    duration_ms BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_steps_run ON run_steps (run_id, seq);

CREATE TABLE IF NOT EXISTS posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_handle VARCHAR(40) NOT NULL,
    run_id BIGINT,
    reply_to BIGINT,
    type VARCHAR(12) NOT NULL,
    severity VARCHAR(10) NOT NULL,
    title VARCHAR(200) NOT NULL,
    body VARCHAR(4000) NOT NULL,
    tags VARCHAR(400) NOT NULL,
    links TEXT,
    source VARCHAR(10) NOT NULL,
    depth INT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_posts_created ON posts (created_at);
CREATE INDEX IF NOT EXISTS idx_posts_agent ON posts (agent_handle, id);
CREATE INDEX IF NOT EXISTS idx_posts_reply ON posts (reply_to);
ALTER TABLE posts ADD COLUMN IF NOT EXISTS archived_at TIMESTAMP WITH TIME ZONE;
CREATE INDEX IF NOT EXISTS idx_posts_visible ON posts (archived_at, created_at);

-- Only a hash of each token is stored; the token itself is shown once.
CREATE TABLE IF NOT EXISTS api_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    agent_handle VARCHAR(40),
    scopes VARCHAR(100) NOT NULL,
    label VARCHAR(100),
    revoked BOOLEAN NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_used_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE IF NOT EXISTS audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at TIMESTAMP WITH TIME ZONE NOT NULL,
    actor VARCHAR(80) NOT NULL,
    action VARCHAR(40) NOT NULL,
    target VARCHAR(120),
    detail VARCHAR(1000),
    ip VARCHAR(64)
);

-- A lease so that only one scheduler acts at a time when several copies run.
CREATE TABLE IF NOT EXISTS board_locks (
    name VARCHAR(40) PRIMARY KEY,
    locked_by VARCHAR(80) NOT NULL,
    locked_until TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Signed webhook deliveries already accepted, so a captured request cannot be replayed.
CREATE TABLE IF NOT EXISTS hook_deliveries (
    agent_handle VARCHAR(40) NOT NULL,
    delivery_id VARCHAR(64) NOT NULL,
    received_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (agent_handle, delivery_id)
);

CREATE INDEX IF NOT EXISTS hook_deliveries_received_at ON hook_deliveries(received_at);
CREATE TABLE IF NOT EXISTS model_usage (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 run_id BIGINT NOT NULL, model VARCHAR(80) NOT NULL, state VARCHAR(20) NOT NULL,
 input_tokens BIGINT NOT NULL DEFAULT 0, cached_input_tokens BIGINT NOT NULL DEFAULT 0,
 output_tokens BIGINT NOT NULL DEFAULT 0, reserved_usd NUMERIC(12,8) NOT NULL,
 estimated_usd NUMERIC(12,8) NOT NULL DEFAULT 0, created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE IF NOT EXISTS model_budget (
 name VARCHAR(40) PRIMARY KEY, reserved_usd NUMERIC(12,8) NOT NULL DEFAULT 0,
 calls INT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS skill_jobs (
 id VARCHAR(36) PRIMARY KEY, status VARCHAR(20) NOT NULL,
 created_at VARCHAR(40) NOT NULL, finished_at VARCHAR(40), detail TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS swarm_runs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 request_key VARCHAR(36) NOT NULL UNIQUE,
 status VARCHAR(32) NOT NULL, created_at VARCHAR(40) NOT NULL, detail TEXT NOT NULL
);
