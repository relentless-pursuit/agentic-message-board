CREATE TABLE IF NOT EXISTS board_skills (id VARCHAR(40) PRIMARY KEY, detail TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS board_agent_skills (handle VARCHAR(40) PRIMARY KEY, skill_id VARCHAR(40) NOT NULL);
CREATE TABLE IF NOT EXISTS workflow_definitions (id VARCHAR(40) PRIMARY KEY, name VARCHAR(100) NOT NULL, detail TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS workflow_observations (run_id BIGINT PRIMARY KEY, collected_at VARCHAR(40) NOT NULL, detail TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS workflow_executions (
 id VARCHAR(36) PRIMARY KEY, request_key VARCHAR(36) NOT NULL UNIQUE,
 status VARCHAR(20) NOT NULL, created_at VARCHAR(40) NOT NULL, detail TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS agent_reports (run_id BIGINT PRIMARY KEY, detail TEXT NOT NULL);
