package dev.agentboard.swarm;

import dev.agentboard.config.BoardProperties;
import dev.agentboard.reason.*;
import org.junit.jupiter.api.*;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import tools.jackson.databind.ObjectMapper;
import java.util.*;
import java.util.concurrent.*;
import java.util.concurrent.atomic.*;
import java.util.zip.ZipInputStream;
import java.io.ByteArrayInputStream;
import static org.assertj.core.api.Assertions.*;

class ResumeSwarmTest {
    final ObjectMapper json=new ObjectMapper();JdbcTemplate db;ModelUsage usage;ResumeSwarmService service;
    final String resume="Alex Example\nBuilt REST APIs.\nWrote tests.\nEducation: B.E. 2022";
    final AtomicInteger calls=new AtomicInteger(),active=new AtomicInteger(),maxActive=new AtomicInteger();
    final Set<Integer> completed=ConcurrentHashMap.newKeySet();
    int failAt=0;CountDownLatch block=null,started=new CountDownLatch(1);
    @BeforeEach void setup(){
        db=new JdbcTemplate(new DriverManagerDataSource("jdbc:h2:mem:"+UUID.randomUUID()+";DB_CLOSE_DELAY=-1","sa",""));
        db.execute("CREATE TABLE swarm_runs(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,request_key VARCHAR(36) UNIQUE,status VARCHAR(32),created_at VARCHAR(40),detail TEXT)");
        db.execute("CREATE TABLE model_budget(name VARCHAR(40) PRIMARY KEY,reserved_usd NUMERIC(12,8),calls INT)");db.update("INSERT INTO model_budget VALUES('openai',0,0)");
        db.execute("CREATE TABLE model_usage(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,run_id BIGINT,model VARCHAR(80),state VARCHAR(20),reserved_usd NUMERIC(12,8),created_at TIMESTAMP,input_tokens BIGINT DEFAULT 0,cached_input_tokens BIGINT DEFAULT 0,output_tokens BIGINT DEFAULT 0,estimated_usd NUMERIC(12,8) DEFAULT 0)");
        var props=new BoardProperties();usage=new ModelUsage(db,props);
        var fake=new OpenAiReasoner(props,json,usage){
            @Override public boolean configured(){return true;}
            @Override public Completion structured(long id,String instructions,String input,Map<String,Object> schema,int maxTokens)throws Exception{
                int n=SwarmSkills.AGENTS.stream().filter(a->instructions.contains("name: "+a.skill()+"\n")).findFirst().orElseThrow().id();
                for(int dependency:SwarmSkills.AGENTS.get(n-1).dependsOn())assertThat(completed).contains(dependency);
                if(n==9){var parsed=json.readTree(input);assertThat(parsed.path("userApprovedResume").asText()).doesNotContain("fabricated claim");assertThat(parsed.path("userMotivation").asText()).isNotBlank();}
                calls.incrementAndGet();int count=active.incrementAndGet();maxActive.accumulateAndGet(count,Math::max);started.countDown();
                long reservation=usage.reserveSwarm(id,"gpt-5.4-nano",0.001);
                try {
                    if(block!=null)block.await(5,TimeUnit.SECONDS);Thread.sleep(25);
                    if(n==failAt){usage.error(reservation);throw new IllegalStateException("Fake provider failure");}
                    List<Map<String,Object>> edits=n==5?List.of(new LinkedHashMap<>(Map.of("before","Built REST APIs.","after","Developed REST APIs.","reason","Clearer verb","evidence","Built REST APIs.")),new LinkedHashMap<>(Map.of("before","Wrote tests.","after","Created automated tests.","reason","Clarity","evidence","Wrote tests."))):List.of();
                    var data=new LinkedHashMap<String,Object>();data.put("summary","Agent "+n+" summary");data.put("items",List.of("Evidence from agent "+n));
                    if(n==5)data.put("edits",edits);if(n==8)data.put("question","What interests you about this role?");if(n==9)data.put("document","Dear team,\nI have built REST APIs and written tests.");
                    usage.success(reservation,50,0,20);completed.add(n);return new Completion(json.valueToTree(data),Map.of("inputTokens",50,"cachedInputTokens",0,"outputTokens",20,"estimatedUsd",0.000035));
                }finally{active.decrementAndGet();}
            }
        };
        service=new ResumeSwarmService(db,json,new SwarmSkills(),fake,usage);
    }
    @AfterEach void close(){if(block!=null)block.countDown();service.close();}
    Map<String,Object> start(){return service.start(UUID.randomUUID().toString(),"Sample",resume,"Backend engineer. REST APIs and automated tests.");}
    Map<String,Object> await(long id,String expected)throws Exception{
        long until=System.nanoTime()+TimeUnit.SECONDS.toNanos(8);
        while(System.nanoTime()<until){var run=service.get(id);if(expected.equals(run.get("status")))return run;if("failed".equals(run.get("status"))&&!expected.equals("failed"))throw new AssertionError(run);Thread.sleep(10);}
        throw new AssertionError("Expected "+expected+": "+service.get(id));
    }
    @Test void tenAgentsCoordinateAndPauseForPartialHumanApproval()throws Exception{
        long id=((Number)start().get("id")).longValue();var review=await(id,"review");
        assertThat(calls.get()).isEqualTo(8);assertThat(maxActive.get()).isEqualTo(2);assertThat(completed).doesNotContain(9,10);
        assertThatThrownBy(()->service.document(id,false)).hasMessageContaining("completed");
        service.approve(id,List.of(new ResumeSwarmService.Choice("edit-1","Implemented REST APIs.")),null,"I enjoy building reliable backend systems.");
        var finalReview=await(id,"final_review");assertThat(calls.get()).isEqualTo(10);
        assertThat(finalReview.get("approvedResume")).isEqualTo(resume.replace("Built REST APIs.","Implemented REST APIs."));
        assertThatThrownBy(()->service.approve(id,List.of(),null,"I enjoy building reliable backend systems.")).hasMessageContaining("review");
        service.finalizeDocuments(id,"My edited cover letter.");assertThat(service.document(id,true)).isEqualTo("My edited cover letter.");
        assertThat(service.document(id,false)).contains("Wrote tests.");assertThat(calls.get()).isEqualTo(10);
        assertThat(((Map<?,?>)review.get("usage")).get("calls")).asString().isEqualTo("8");
    }
    @Test void fullAcceptanceAndCustomResumePreserveUserAuthority()throws Exception{
        long id=((Number)start().get("id")).longValue();await(id,"review");
        service.approve(id,List.of(new ResumeSwarmService.Choice("edit-1","Developed REST APIs."),new ResumeSwarmService.Choice("edit-2","Created automated tests.")),"My own complete résumé.","I enjoy improving developer tools.");
        assertThat(await(id,"final_review").get("approvedResume")).isEqualTo("My own complete résumé.");
    }
    @Test void missingKeyRejectsNewResumeExecution(){
        service.close();var props=new BoardProperties();var noKey=new OpenAiReasoner(props,json,usage){@Override public boolean configured(){return false;}};
        service=new ResumeSwarmService(db,json,new SwarmSkills(),noKey,usage);
        assertThat(service.options().get("configured")).isEqualTo(false);
        assertThatThrownBy(()->service.start(UUID.randomUUID().toString(),"Fixture","Resume text","Job text")).hasMessageContaining("OPENAI_API_KEY");
    }
    @Test void duplicateSubmissionsDoNotStartMoreAgents()throws Exception{
        String key=UUID.randomUUID().toString();long id=((Number)service.start(key,"Sample",resume,"Java role").get("id")).longValue();
        assertThat(((Number)service.start(key,"Sample",resume,"Java role").get("id")).longValue()).isEqualTo(id);await(id,"review");assertThat(calls.get()).isEqualTo(8);
        service.approve(id,List.of(),null,"I enjoy building backend systems.");assertThat(await(id,"final_review").get("approvedResume")).isEqualTo(resume);
    }
    @Test void failedAgentBlocksItsDependantsWithoutRetry()throws Exception{
        failAt=3;long id=((Number)start().get("id")).longValue();var failed=await(id,"failed");
        assertThat(calls.get()).isEqualTo(3);assertThat(completed).doesNotContain(4,5,6,7,8,9,10);
        assertThat(failed.get("error")).isEqualTo("Fake provider failure");
    }
    @Test void cancellationStopsNewStagesAndDoesNotResumeOnViewing()throws Exception{
        block=new CountDownLatch(1);long id=((Number)start().get("id")).longValue();assertThat(started.await(3,TimeUnit.SECONDS)).isTrue();
        service.cancel(id);block.countDown();await(id,"cancelled");Thread.sleep(100);service.get(id);service.options();
        assertThat(calls.get()).isLessThanOrEqualTo(2);assertThat(completed).doesNotContain(3,9,10);
    }
    @Test void editsMustLocateOneUniqueNonOverlappingOriginalPassage(){
        var first=new LinkedHashMap<String,Object>(Map.of("before","same","after","new","reason","Clarity","evidence","same"));var second=new LinkedHashMap<String,Object>(Map.of("before","missing","after","new","reason","Clarity","evidence","missing"));
        var result=new LinkedHashMap<String,Object>(Map.of("edits",List.of(first,second)));ResumeSwarmService.validateEdits(result,"same same");
        assertThat(first.get("valid")).isEqualTo(false);assertThat(second.get("valid")).isEqualTo(false);
        assertThatThrownBy(()->ResumeSwarmService.applyEdits("same same",List.of(first),List.of(new ResumeSwarmService.Choice("edit-1","new")))).hasMessageContaining("cannot be applied");
    }
    @Test void perSwarmBudgetAndAttemptCapsPersist(){
        db.update("INSERT INTO swarm_runs(request_key,status,created_at,detail) VALUES(?,'review','now','{}')",UUID.randomUUID().toString());
        for(int n=0;n<10;n++)usage.reserveSwarm(1,"gpt-5.4-nano",0.001);
        assertThatThrownBy(()->usage.reserveSwarm(1,"gpt-5.4-nano",0.001)).hasMessageContaining("10-call");
        db.update("INSERT INTO swarm_runs(request_key,status,created_at,detail) VALUES(?,'review','now','{}')",UUID.randomUUID().toString());
        usage.reserveSwarm(2,"gpt-5.4-nano",0.099);
        assertThatThrownBy(()->usage.reserveSwarm(2,"gpt-5.4-nano",0.002)).hasMessageContaining("reservation limit");
        assertThat(db.queryForObject("SELECT calls FROM model_budget WHERE name='openai'",Integer.class)).isEqualTo(11);
    }
    @Test void wordExportsPreserveApprovedTextAndEscapeXml()throws Exception{
        byte[] file=SwarmDocuments.docx("Alex & Example\n<Engineer>\nRésumé");String document=null;
        try(var zip=new ZipInputStream(new ByteArrayInputStream(file))){for(var entry=zip.getNextEntry();entry!=null;entry=zip.getNextEntry())if(entry.getName().equals("word/document.xml"))document=new String(zip.readAllBytes(),java.nio.charset.StandardCharsets.UTF_8);}
        assertThat(document).contains("Alex &amp; Example","&lt;Engineer&gt;","Résumé");
        var factory=javax.xml.parsers.DocumentBuilderFactory.newInstance();factory.newDocumentBuilder().parse(new ByteArrayInputStream(document.getBytes(java.nio.charset.StandardCharsets.UTF_8)));
    }
}
