package dev.agentboard.reason;

import dev.agentboard.config.BoardProperties;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import static org.assertj.core.api.Assertions.*;
import java.util.UUID;

class ModelUsageTest {
    private JdbcTemplate jdbc;
    private ModelUsage ledger(int calls,double budget) {
        jdbc=new JdbcTemplate(new DriverManagerDataSource("jdbc:h2:mem:usage-"+UUID.randomUUID()+";DB_CLOSE_DELAY=-1","sa",""));
        jdbc.execute("CREATE TABLE model_budget(name VARCHAR PRIMARY KEY,reserved_usd DECIMAL(12,8),calls INT)");
        jdbc.execute("INSERT INTO model_budget VALUES('openai',0,0)");
        jdbc.execute("CREATE TABLE model_usage(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,run_id BIGINT,model VARCHAR,state VARCHAR,input_tokens BIGINT DEFAULT 0,cached_input_tokens BIGINT DEFAULT 0,output_tokens BIGINT DEFAULT 0,reserved_usd DECIMAL(12,8),estimated_usd DECIMAL(12,8) DEFAULT 0,created_at TIMESTAMP WITH TIME ZONE)");
        var props=new BoardProperties();props.getOpenai().setMaxCalls(calls);props.getOpenai().setBudgetUsd(budget);
        return new ModelUsage(jdbc,props);
    }
    @Test void attemptCapPreventsFurtherPaidRequestsAndSurvivesFailures() {
        var usage=ledger(2,1);usage.error(usage.reserve(1,"gpt-5.4-nano",0.01));usage.reserve(2,"gpt-5.4-nano",0.01);
        assertThatThrownBy(()->usage.reserve(3,"gpt-5.4-nano",0.01)).isInstanceOf(IllegalStateException.class);
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM model_usage",Integer.class)).isEqualTo(2);
    }
    @Test void dollarReservationRejectsNextRequestBeforeCallingProvider() {
        var usage=ledger(10,0.015);usage.reserve(1,"gpt-5.4-nano",0.01);
        assertThatThrownBy(()->usage.reserve(2,"gpt-5.4-nano",0.01)).isInstanceOf(IllegalStateException.class);
    }
    @Test void cachedAndOutputTokensUseSeparateRates() {
        var usage=ledger(1,1);long id=usage.reserve(1,"gpt-5.4-nano",0.01);
        usage.success(id,1000,400,200);
        assertThat(jdbc.queryForObject("SELECT estimated_usd FROM model_usage WHERE id=?",Double.class,id)).isCloseTo(0.000378,within(0.00000001));
        assertThat(jdbc.queryForObject("SELECT cached_input_tokens FROM model_usage WHERE id=?",Long.class,id)).isEqualTo(400);
    }
}
